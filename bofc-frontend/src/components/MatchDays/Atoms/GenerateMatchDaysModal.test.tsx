import React from "react";
import { fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import GenerateMatchDaysModal from "./GenerateMatchDaysModal";

// SPEC: spec-a6f59e - Generate creates exactly N Match Days, N prefilled from the "Auto
// generated match number" setting and changeable for one run without touching the setting.

const mockCreateMatchDay = jest.fn();
const mockUpdateSystemSettings = jest.fn();
const mockAutoGeneratedMatchNumberQuery = jest.fn();

jest.mock("react-toastify", () => ({ toast: { success: jest.fn(), error: jest.fn() } }));
jest.mock("../../../state/features/vanues/vanuesSlice", () => ({
    useGetVanuesQuery: () => ({ data: { content: [{ id: 5, name: "Club Arena" }] }, isLoading: false }),
}));
jest.mock("../../../state/features/matchDays/matchDaysSlice", () => ({
    useCreateMatchDayMutation: () => [mockCreateMatchDay],
}));
jest.mock("../../../state/features/settings/settingsSlice", () => ({
    useGetAutoGeneratedMatchNumberQuery: () => mockAutoGeneratedMatchNumberQuery(),
    useUpdateSystemSettingsMutation: () => [mockUpdateSystemSettings],
}));

const openModal = () => fireEvent.click(screen.getByText("Generate"));
const startMonthInput = () => screen.getByLabelText("Start Month");
const countInput = () => screen.getByLabelText("Number of Match Days");
const submitButton = () => screen.getByRole("button", { name: /match day/i });

const fillAndSubmit = (startMonth: string) => {
    fireEvent.change(startMonthInput(), { target: { value: startMonth } });
    const venueSelect = screen
        .getAllByRole("combobox")
        .find((select) => within(select).queryByRole("option", { name: "Club Arena" })) as HTMLSelectElement;
    fireEvent.change(venueSelect, { target: { value: "5" } });
    fireEvent.click(submitButton());
};

const createdNames = () => mockCreateMatchDay.mock.calls.map(([body]) => body.matchDayName);

beforeEach(() => {
    mockCreateMatchDay.mockReset();
    mockCreateMatchDay.mockImplementation(() => ({ unwrap: () => Promise.resolve({}) }));
    mockUpdateSystemSettings.mockReset();
    mockAutoGeneratedMatchNumberQuery.mockReset();
});

describe("GenerateMatchDaysModal", () => {
    it("prefills the setting's count of 2 and creates Match Days on the first two matching dates", async () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: { content: 2 } });
        render(<GenerateMatchDaysModal />);
        openModal();

        expect(countInput()).toHaveValue(2);
        fireEvent.change(startMonthInput(), { target: { value: "2026-09" } });
        expect(screen.getByText("Sep 2, Sep 9")).toBeInTheDocument();
        expect(submitButton()).toHaveTextContent("Generate 2 Match Days");

        fillAndSubmit("2026-09");
        await waitFor(() => expect(mockCreateMatchDay).toHaveBeenCalledTimes(2));
        expect(mockCreateMatchDay).toHaveBeenNthCalledWith(1, {
            matchDayName: "Match Day - Sep 2",
            matchDayDate: "2026-09-02T18:00:00",
            durationMinutes: 90,
            venueId: 5,
            defaultMatchDay: false,
        });
        expect(mockCreateMatchDay).toHaveBeenNthCalledWith(2, expect.objectContaining({
            matchDayName: "Match Day - Sep 9",
            matchDayDate: "2026-09-09T18:00:00",
            defaultMatchDay: false,
        }));
    });

    it("with a count of 6 runs past a month of four Wednesdays into the next month", async () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: { content: 6 } });
        render(<GenerateMatchDaysModal />);
        openModal();

        fillAndSubmit("2026-02");
        await waitFor(() => expect(mockCreateMatchDay).toHaveBeenCalledTimes(6));
        expect(createdNames()).toEqual([
            "Match Day - Feb 4",
            "Match Day - Feb 11",
            "Match Day - Feb 18",
            "Match Day - Feb 25",
            "Match Day - Mar 4",
            "Match Day - Mar 11",
        ]);
    });

    it("uses a changed count for that run only and never saves it to the setting", async () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: { content: 2 } });
        render(<GenerateMatchDaysModal />);
        openModal();

        fireEvent.change(countInput(), { target: { value: "3" } });
        fillAndSubmit("2026-09");
        await waitFor(() => expect(mockCreateMatchDay).toHaveBeenCalledTimes(3));
        expect(createdNames()).toEqual(["Match Day - Sep 2", "Match Day - Sep 9", "Match Day - Sep 16"]);
        expect(mockUpdateSystemSettings).not.toHaveBeenCalled();

        // Every create succeeded, so the modal closed; reopened, it follows the setting again.
        await waitFor(() => expect(screen.queryByLabelText("Number of Match Days")).toBeNull());
        openModal();
        expect(countInput()).toHaveValue(2);
    });

    it("disables submit with no start month, or a count outside 1 to 8", () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: { content: 2 } });
        render(<GenerateMatchDaysModal />);
        openModal();

        fireEvent.change(startMonthInput(), { target: { value: "" } });
        expect(submitButton()).toBeDisabled();

        fireEvent.change(startMonthInput(), { target: { value: "2026-09" } });
        expect(submitButton()).toBeEnabled();

        for (const value of ["0", "9", ""]) {
            fireEvent.change(countInput(), { target: { value } });
            expect(submitButton()).toBeDisabled();
            expect(screen.getByText("Please enter a number from 1 to 8!")).toBeInTheDocument();
        }
        expect(mockCreateMatchDay).not.toHaveBeenCalled();
    });

    it("falls back to 2 when the setting can't be loaded", () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: undefined, isError: true });
        render(<GenerateMatchDaysModal />);
        openModal();
        expect(countInput()).toHaveValue(2);
    });

    it("takes the setting's value when it arrives after the modal opened", () => {
        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: undefined, isLoading: true });
        const { rerender } = render(<GenerateMatchDaysModal />);
        openModal();
        expect(countInput()).toHaveValue(2);

        mockAutoGeneratedMatchNumberQuery.mockReturnValue({ data: { content: 5 } });
        rerender(<GenerateMatchDaysModal />);
        expect(countInput()).toHaveValue(5);
    });
});
