import { useMemo, useState } from "react";
import { toast } from "react-toastify";
import dayjs from "dayjs";
import { ThunderboltOutlined } from "@ant-design/icons";
import { useGetVanuesQuery } from "../../../state/features/vanues/vanuesSlice";
import { useCreateMatchDayMutation } from "../../../state/features/matchDays/matchDaysSlice";
import { useGetAutoGeneratedMatchNumberQuery } from "../../../state/features/settings/settingsSlice";
import {
  AUTO_GENERATED_MATCH_NUMBER_DEFAULT,
  AUTO_GENERATED_MATCH_NUMBER_MAX,
  AUTO_GENERATED_MATCH_NUMBER_MIN,
  generateMatchDayDates,
  isValidGenerateCount,
} from "../../../utils/matchDayGeneration";
import Modal from "../../ui/modal";
import Button from "../../ui/button";
import FormInput from "../../ui/form-input";
import FormSelect from "../../ui/form-select";

// SPEC: spec-a6f59e

const WEEKDAY_OPTIONS = [
  { value: "0", label: "Sunday" },
  { value: "1", label: "Monday" },
  { value: "2", label: "Tuesday" },
  { value: "3", label: "Wednesday" },
  { value: "4", label: "Thursday" },
  { value: "5", label: "Friday" },
  { value: "6", label: "Saturday" },
];

interface FormValues {
  month: string; // YYYY-MM - the start month
  weekday: string; // 0-6, dayjs .day() convention
  time: string; // HH:mm
  durationMinutes: string;
  venueId: string;
  namePrefix: string;
}

const emptyValues: FormValues = {
  month: dayjs().format("YYYY-MM"),
  weekday: "3", // Wednesday - the club's standing match day (see notification/dashboard copy elsewhere)
  time: "18:00",
  durationMinutes: "90",
  venueId: "",
  namePrefix: "Match Day",
};

/**
 * Bulk-creates exactly N Match Days on a chosen weekday, week by week from the
 * first matching date on or after the 1st of a chosen start month and running
 * into later months as needed, instead of clicking "+ New Match Day" once per
 * date. N is prefilled from Settings' "Auto generated match number" (read via
 * its own endpoint, since coordinators can't read the rest of settings) and
 * falls back to 2 if that can't be loaded; it can be changed here for one run
 * only, without writing the setting back.
 * Reuses the same createMatchDay mutation CreateMatchDayModal.tsx uses for a
 * single entry - just looped, so it inherits the same validation/persistence
 * path rather than a separate bulk backend endpoint.
 */
export default function GenerateMatchDaysModal() {
  const { data: venuesData, isLoading: isVenuesLoading } = useGetVanuesQuery();
  const { data: autoGeneratedMatchNumberData } = useGetAutoGeneratedMatchNumberQuery();
  const [createMatchDay] = useCreateMatchDayMutation();
  const [open, setOpen] = useState(false);
  const [values, setValues] = useState<FormValues>(emptyValues);
  // null = follow the setting (also once it arrives late); a string = this run's own count.
  const [countOverride, setCountOverride] = useState<string | null>(null);
  const [errors, setErrors] = useState<Partial<Record<keyof FormValues, string>>>({});
  const [isGenerating, setIsGenerating] = useState(false);

  const settingCount = isValidGenerateCount(Number(autoGeneratedMatchNumberData?.content))
    ? Number(autoGeneratedMatchNumberData?.content)
    : AUTO_GENERATED_MATCH_NUMBER_DEFAULT;
  const countValue = countOverride ?? String(settingCount);
  const count = Number(countValue);
  const isCountValid = isValidGenerateCount(count);

  const setField = <K extends keyof FormValues>(key: K, val: FormValues[K]) => {
    setValues((prev) => ({ ...prev, [key]: val }));
  };

  const resetForm = () => {
    setValues(emptyValues);
    setCountOverride(null);
    setErrors({});
  };

  const closeModal = () => {
    if (isGenerating) return;
    setOpen(false);
    resetForm();
  };

  // The first `count` dates on the chosen weekday, from the start month onward.
  const matchingDates = useMemo(
    () => generateMatchDayDates(values.month, Number(values.weekday), count),
    [values.month, values.weekday, count]
  );

  const validate = () => {
    const next: Partial<Record<keyof FormValues, string>> = {};
    if (!values.month) next.month = "Please select a start month!";
    if (!values.time) next.time = "Please select a time!";
    if (!values.venueId) next.venueId = "Please select a venue!";
    if (!values.namePrefix.trim()) next.namePrefix = "Please enter a name prefix!";
    setErrors(next);
    return Object.keys(next).length === 0;
  };

  const handleGenerate = async () => {
    if (isGenerating) return;
    if (!validate() || !isCountValid) return;
    if (matchingDates.length === 0) {
      toast.error("No matching dates from that start month");
      return;
    }

    setIsGenerating(true);
    let successCount = 0;
    // Sequential, not Promise.all - createMatchDay hits the same table each
    // time; racing several at once risks the kind of unique-constraint 500s
    // this app has hit before elsewhere (see the duplicate-check fixes in
    // PlayerService/AcChart) rather than a clean per-item error.
    for (const date of matchingDates) {
      const matchDayDateNaive = `${date.format("YYYY-MM-DD")}T${values.time}:00`;
      try {
        await createMatchDay({
          matchDayName: `${values.namePrefix} - ${date.format("MMM D")}`,
          matchDayDate: matchDayDateNaive,
          durationMinutes: values.durationMinutes ? Number(values.durationMinutes) : undefined,
          venueId: Number(values.venueId),
          defaultMatchDay: false,
        }).unwrap();
        successCount++;
      } catch (err) {
        console.error(`Failed to create Match Day for ${date.format("YYYY-MM-DD")}`, err);
      }
    }

    setIsGenerating(false);
    if (successCount > 0) {
      toast.success(`Created ${successCount} of ${matchingDates.length} Match Days`);
    }
    if (successCount === matchingDates.length) {
      setOpen(false);
      resetForm();
    }
  };

  return (
    <div>
      <Button variant="outline" startIcon={<ThunderboltOutlined />} onClick={() => setOpen(true)}>
        Generate
      </Button>
      <Modal isOpen={open} onClose={closeModal} title="Generate Match Days" className="max-w-[560px]">
        {isVenuesLoading ? null : (
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleGenerate();
            }}
            className="flex flex-col gap-4"
          >
            <div className="grid grid-cols-2 gap-3">
              <FormInput
                id="generate-match-days-start-month"
                type="month"
                label="Start Month"
                value={values.month}
                onChange={(e) => setField("month", e.target.value)}
                error={errors.month}
              />
              <FormSelect
                label="Day of Week"
                value={values.weekday}
                onChange={(e) => setField("weekday", e.target.value)}
                options={WEEKDAY_OPTIONS}
              />
            </div>

            <FormInput
              id="generate-match-days-count"
              type="number"
              min={AUTO_GENERATED_MATCH_NUMBER_MIN}
              max={AUTO_GENERATED_MATCH_NUMBER_MAX}
              step={1}
              label="Number of Match Days"
              hint="Prefilled from Settings' Auto generated match number - a change here applies to this run only."
              value={countValue}
              onChange={(e) => setCountOverride(e.target.value)}
              error={
                isCountValid
                  ? undefined
                  : `Please enter a number from ${AUTO_GENERATED_MATCH_NUMBER_MIN} to ${AUTO_GENERATED_MATCH_NUMBER_MAX}!`
              }
            />

            <div className="grid grid-cols-2 gap-3">
              <FormInput
                type="time"
                label="Time"
                value={values.time}
                onChange={(e) => setField("time", e.target.value)}
                error={errors.time}
              />
              <FormInput
                type="number"
                min={10}
                max={720}
                label="Duration (minutes)"
                value={values.durationMinutes}
                onChange={(e) => setField("durationMinutes", e.target.value)}
              />
            </div>

            <FormSelect
              label="Venue"
              placeholder="Please select a venue"
              value={values.venueId}
              disabled={isVenuesLoading}
              onChange={(e) => setField("venueId", e.target.value)}
              error={errors.venueId}
              options={venuesData?.content.map((venue: any) => ({ value: venue.id, label: venue.name })) || []}
            />

            <FormInput
              label="Name Prefix"
              placeholder="e.g. Match Day"
              hint={`Each entry is named "${values.namePrefix || "prefix"} - date", e.g. "Match Day - Sep 2".`}
              value={values.namePrefix}
              onChange={(e) => setField("namePrefix", e.target.value)}
              error={errors.namePrefix}
            />

            <div className="rounded-lg border border-gray-200 bg-gray-50 p-3 text-theme-xs text-gray-600 dark:border-[var(--color-rule)] dark:bg-[var(--color-paper-2)] dark:text-gray-300">
              {matchingDates.length === 0 ? (
                `Choose a start month and from ${AUTO_GENERATED_MATCH_NUMBER_MIN} to ${AUTO_GENERATED_MATCH_NUMBER_MAX} Match Days.`
              ) : (
                <>
                  <span className="font-semibold">{matchingDates.length} Match Day{matchingDates.length > 1 ? "s" : ""} will be created:</span>{" "}
                  {matchingDates.map((d) => d.format("MMM D")).join(", ")}
                </>
              )}
            </div>

            <Button
              type="submit"
              className="w-full"
              disabled={isGenerating || !values.month || !isCountValid || matchingDates.length === 0}
            >
              {isGenerating ? `Generating... ` : `Generate ${matchingDates.length || ""} Match Day${matchingDates.length === 1 ? "" : "s"}`}
            </Button>
          </form>
        )}
      </Modal>
    </div>
  );
}
